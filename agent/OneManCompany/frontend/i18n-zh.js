  function translateText(value) {
    if (typeof value !== 'string' || !/[A-Za-z]/.test(value)) return value;
    const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/);
    const leading = match ? match[1] : '';
    let core = match ? match[2] : value;
    const trailing = match ? match[3] : '';
    if (!core) return value;

    if (exact.has(core)) return leading + exact.get(core) + trailing;
    let translated = core;
    for (const [pattern, replacement] of phraseRules) {
      if (pattern.test(translated)) translated = translated.replace(pattern, replacement);
    }
    if (translated !== core) core = translated;
    for (const [source, target] of sentenceReplacements) {
      if (core.includes(source)) core = core.split(source).join(target);
    }
    return leading + core + trailing;
  }

  function shouldSkip(node) {
    const parent = node.parentElement;
    if (!parent) return true;
    return Boolean(parent.closest('script,style,code,pre,textarea,.xterm,.xterm-screen,.execution-log-content'));
  }

  function translateElement(root) {
    if (!root) return;
    if (root.nodeType === Node.TEXT_NODE) {
      if (!shouldSkip(root)) {
        const next = translateText(root.nodeValue);
        if (next !== root.nodeValue) root.nodeValue = next;
      }
      return;
    }
    if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE && root.nodeType !== Node.DOCUMENT_FRAGMENT_NODE) return;

    const el = root.nodeType === Node.ELEMENT_NODE ? root : null;
    if (el) {
      for (const attr of ['placeholder', 'title', 'aria-label']) {
        if (el.hasAttribute && el.hasAttribute(attr)) {
          const oldValue = el.getAttribute(attr);
          const nextValue = translateText(oldValue);
          if (nextValue !== oldValue) el.setAttribute(attr, nextValue);
        }
      }
    }

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    for (const node of nodes) {
      if (!shouldSkip(node)) {
        const next = translateText(node.nodeValue);
        if (next !== node.nodeValue) node.nodeValue = next;
      }
    }

    const elements = root.querySelectorAll ? root.querySelectorAll('[placeholder],[title],[aria-label]') : [];
    for (const item of elements) {
      for (const attr of ['placeholder', 'title', 'aria-label']) {
        if (!item.hasAttribute(attr)) continue;
        const oldValue = item.getAttribute(attr);
        const nextValue = translateText(oldValue);
        if (nextValue !== oldValue) item.setAttribute(attr, nextValue);
      }
    }
  }

  const nativeConfirm = window.confirm.bind(window);
  const nativeAlert = window.alert.bind(window);
  const nativePrompt = window.prompt.bind(window);
  window.confirm = (message) => nativeConfirm(translateText(String(message)));
  window.alert = (message) => nativeAlert(translateText(String(message)));
  window.prompt = (message, defaultValue) => nativePrompt(translateText(String(message)), defaultValue);

